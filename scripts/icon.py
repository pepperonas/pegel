#!/usr/bin/env python3
"""One source for the launcher icon.

    python3 scripts/icon.py            # from the repo root

writes the adaptive-icon layers and the status-bar icon into app/src/main/res/drawable, and
docs/icon.svg (full bleed) + docs/mark.svg (rounded, for the website). Geometry is computed, not typed:
five level bars and an amber peak-hold cap over the tallest, inside the 66 dp safe zone.
"""
import sys, pathlib
W=8.0; GAP=3.6; N=5; BOTTOM=77.0
HEIGHTS=[16,30,23,41,21]
X0=(108-(N*W+(N-1)*GAP))/2
PEAK=3   # index of the bar that carries the amber peak-hold cap
CAP_H=4.0; CAP_GAP=3.6
def pill(x,y,w,h):
    r=w/2 if h>=w else h/2
    return (f"M{x+r:.2f},{y:.2f}h{w-2*r:.2f}a{r:.2f},{r:.2f} 0,0 1,{r:.2f} {r:.2f}v{h-2*r:.2f}"
            f"a{r:.2f},{r:.2f} 0,0 1,-{r:.2f} {r:.2f}h-{w-2*r:.2f}a{r:.2f},{r:.2f} 0,0 1,-{r:.2f} -{r:.2f}"
            f"v-{h-2*r:.2f}a{r:.2f},{r:.2f} 0,0 1,{r:.2f} -{r:.2f}z")
bars=[(X0+i*(W+GAP),BOTTOM-h,W,h) for i,h in enumerate(HEIGHTS)]
bx,by,_,_=bars[PEAK]
cap=(bx,by-CAP_GAP-CAP_H,W,CAP_H)
BAR_D=" ".join(pill(*b) for b in bars); CAP_D=pill(*cap)
def svg(mask=None,size=108,mono=False):
    clip={"circle":'<circle cx="54" cy="54" r="36"/>',"squircle":'<rect x="18" y="18" width="72" height="72" rx="20"/>',None:'<rect width="108" height="108"/>'}[mask]
    fg = f'<path d="{BAR_D} {CAP_D}" fill="#fff"/>' if mono else f'<path d="{BAR_D}" fill="url(#bar)"/><path d="{CAP_D}" fill="url(#cap)"/>'
    bg = '<rect width="108" height="108" fill="#3a4a35"/>' if mono else '<rect width="108" height="108" fill="url(#bg)"/><rect width="108" height="108" fill="url(#glow)"/>'
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="{'18 18 72 72' if mask else '0 0 108 108'}" width="{size}" height="{size}">
<defs>
<linearGradient id="bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#1D2418"/><stop offset="1" stop-color="#0A0D08"/></linearGradient>
<radialGradient id="glow" cx="54" cy="64" r="40" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#A0D57B" stop-opacity=".20"/><stop offset="1" stop-color="#A0D57B" stop-opacity="0"/></radialGradient>
<linearGradient id="bar" x1="0" y1="{BOTTOM-max(HEIGHTS)}" x2="0" y2="{BOTTOM}" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#C9F7A6"/><stop offset="1" stop-color="#7DBB55"/></linearGradient>
<linearGradient id="cap" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#FFD067"/><stop offset="1" stop-color="#F2B233"/></linearGradient>
<clipPath id="m">{clip}</clipPath></defs>
<g clip-path="url(#m)">{bg}{fg}</g></svg>'''
ROOT=pathlib.Path(__file__).resolve().parent.parent
out=ROOT/"app/src/main/res/drawable"
(ROOT/"docs/icon.svg").write_text(svg(None,512))
(ROOT/"docs/mark.svg").write_text(svg("squircle",512))
if out:
    V='<?xml version="1.0" encoding="utf-8"?>\n'
    head='<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    xmlns:aapt="http://schemas.android.com/aapt"\n    android:width="108dp" android:height="108dp"\n    android:viewportWidth="108" android:viewportHeight="108">\n'
    def grad(kind,attrs,stops):
        s="".join(f'                <item android:offset="{o}" android:color="{c}" />\n' for o,c in stops)
        return f'        <aapt:attr name="android:fillColor">\n            <gradient android:type="{kind}" {attrs}>\n{s}            </gradient>\n        </aapt:attr>\n'
    (out/"ic_launcher_background.xml").write_text(V+"<!-- Generated by scripts/icon.py. A vector, not a shape: the About section paints this layer with painterResource. -->\n"+head+
      '    <path android:pathData="M0,0h108v108h-108z">\n'+grad("linear",'android:startX="54" android:startY="0" android:endX="54" android:endY="108"',[(0,"#FF1D2418"),(1,"#FF0A0D08")])+'    </path>\n'+
      '    <path android:pathData="M0,0h108v108h-108z">\n'+grad("radial",'android:centerX="54" android:centerY="64" android:gradientRadius="40"',[(0,"#33A0D57B"),(1,"#00A0D57B")])+'    </path>\n</vector>\n')
    (out/"ic_launcher_foreground.xml").write_text(V+"<!-- Generated by scripts/icon.py -->\n"+head+
      f'    <path android:pathData="{BAR_D}">\n'+grad("linear",f'android:startX="54" android:startY="{BOTTOM-max(HEIGHTS)}" android:endX="54" android:endY="{BOTTOM}"',[(0,"#FFC9F7A6"),(1,"#FF7DBB55")])+'    </path>\n'+
      f'    <path android:pathData="{CAP_D}">\n'+grad("linear",f'android:startX="{cap[0]}" android:startY="0" android:endX="{cap[0]+W}" android:endY="0"',[(0,"#FFFFD067"),(1,"#FFF2B233")])+'    </path>\n</vector>\n')
    (out/"ic_launcher_monochrome.xml").write_text(V+"<!-- Generated by scripts/icon.py -->\n"+head.replace('    xmlns:aapt="http://schemas.android.com/aapt"\n','')+
      f'    <path android:fillColor="#FFFFFF" android:pathData="{BAR_D} {CAP_D}" />\n</vector>\n')
    # Status bar: the same mark in a 24 dp box (the 60 dp centre of the launcher grid, scaled 0.4).
    k=0.4; o=-24*k
    sb=" ".join(pill(x*k+o,y*k+o,w*k,h*k) for x,y,w,h in bars+[cap])
    (out/"ic_stat_pegel.xml").write_text(V+"<!-- Generated by scripts/icon.py -->\n"+
      '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp" android:height="24dp"\n    android:viewportWidth="24" android:viewportHeight="24">\n'+
      f'    <path android:fillColor="#FFFFFF" android:pathData="{sb}" />\n</vector>\n')
