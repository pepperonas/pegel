#!/usr/bin/env python3
"""Builds app/src/main/assets/headphones.tsv from the AutoEq project.

AutoEq (https://github.com/jaakkopasanen/AutoEq, MIT) publishes, per headphone model, a
`FixedBandEQ.txt` with ten peaking filters at exactly Pegel's band centres. This script takes the
one result AutoEq recommends per model (results/README.md) at a pinned commit and writes one line
per model:

    name <TAB> source <TAB> form <TAB> preamp <TAB> g31 ... g16k

Usage: python3 scripts/autoeq.py [--cache DIR]
The output is generated — never edit it by hand; change COMMIT and run this again.
"""
import argparse
import re
import subprocess
import sys
import urllib.parse
from pathlib import Path

REPO = "https://github.com/jaakkopasanen/AutoEq.git"
# Pinned so that a build is reproducible and a data change is a visible diff.
COMMIT = "7ae0f56d53074872b028649617a22bbb4232feb7"
BANDS = [31, 62, 125, 250, 500, 1000, 2000, 4000, 8000, 16000]
ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app/src/main/assets/headphones.tsv"
NOTICE = ROOT / "docs/AUTOEQ-NOTICE.md"

# Names and paths contain brackets ("(ANC Off)"), hence the anchors instead of [^)]+.
LINK = re.compile(r"^- \[(?P<name>.+)\]\((?P<path>\./.+)\)\s*$")
FILTER = re.compile(r"^Filter \d+: ON PK Fc (\d+) Hz Gain (-?\d+(?:\.\d+)?) dB Q 1\.41\s*$")
PREAMP = re.compile(r"^Preamp: (-?\d+(?:\.\d+)?) dB\s*$")


def git(*args, cwd=None):
    subprocess.run(["git", *args], cwd=cwd, check=True)


def checkout(cache: Path):
    """A blobless, sparse checkout: only the index and the ten-band files are downloaded."""
    if not (cache / ".git").exists():
        cache.mkdir(parents=True, exist_ok=True)
        git("init", "-q", cwd=cache)
        git("remote", "add", "origin", REPO, cwd=cache)
        git("config", "core.sparseCheckout", "true", cwd=cache)
        (cache / ".git/info/sparse-checkout").write_text("/LICENSE\n/results/README.md\n*FixedBandEQ.txt\n")
    git("fetch", "-q", "--depth", "1", "--filter=blob:none", "origin", COMMIT, cwd=cache)
    git("checkout", "-q", "FETCH_HEAD", cwd=cache)


def parse_fixed_band(text: str):
    """(preamp, [ten gains]) or None when the file is not the ten bands Pegel has."""
    lines = [l for l in text.splitlines() if l.strip()]
    if len(lines) != 11:
        return None
    m = PREAMP.match(lines[0])
    if not m:
        return None
    gains = []
    for want, line in zip(BANDS, lines[1:]):
        f = FILTER.match(line)
        if not f or int(f.group(1)) != want:
            return None
        gains.append(float(f.group(2)))
    return float(m.group(1)), gains


def fmt(v: float) -> str:
    return ("%.1f" % v).replace("-0.0", "0.0")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default=str(ROOT / "build/autoeq"))
    args = ap.parse_args()
    cache = Path(args.cache)
    checkout(cache)

    rows, skipped, seen = [], [], set()
    for line in (cache / "results/README.md").read_text(encoding="utf-8").splitlines():
        m = LINK.match(line)
        if not m:
            continue
        name = " ".join(m.group("name").split())
        rel = urllib.parse.unquote(m.group("path"))[2:]
        folder = cache / "results" / rel
        parts = Path(rel).parts  # source / rig-or-form / model
        files = sorted(folder.glob("*FixedBandEQ.txt")) if folder.is_dir() else []
        parsed = parse_fixed_band(files[0].read_text(encoding="utf-8")) if files else None
        if parsed is None or "\t" in name or name.lower() in seen:
            skipped.append(name)
            continue
        seen.add(name.lower())
        form = next((f for f in ("in-ear", "over-ear", "earbud") if any(f in p for p in parts)), "")
        preamp, gains = parsed
        rows.append("\t".join([name, parts[0], form, fmt(preamp), *map(fmt, gains)]))

    if len(rows) < 3000:
        sys.exit(f"only {len(rows)} models parsed — the layout of AutoEq changed, refusing to write")
    rows.sort(key=str.lower)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(rows) + "\n", encoding="utf-8")

    sources = sorted({r.split("\t")[1] for r in rows}, key=str.lower)
    NOTICE.write_text(
        "# Headphone corrections: AutoEq\n\n"
        "`app/src/main/assets/headphones.tsv` is generated by `scripts/autoeq.py` from\n"
        f"[AutoEq](https://github.com/jaakkopasanen/AutoEq) at commit `{COMMIT}`: the ten-band\n"
        "result (`FixedBandEQ.txt`) AutoEq recommends for each model, "
        f"{len(rows)} models.\n\n"
        "Measurements behind these results were made by: " + ", ".join(sources) + ".\n"
        "AutoEq names its sources in its README and states no separate licence for the data.\n\n"
        "## AutoEq licence (MIT)\n\n```\n" + (cache / "LICENSE").read_text(encoding="utf-8").strip() + "\n```\n",
        encoding="utf-8",
    )
    print(f"{len(rows)} models written, {len(skipped)} skipped; {OUT.stat().st_size} bytes")
    if skipped:
        print("skipped (first 10):", "; ".join(skipped[:10]))


if __name__ == "__main__":
    main()
