// WebMCP tools: lets an AI agent in the browser ask this page for facts and actions directly instead of
// scraping it (https://developer.chrome.com/docs/ai/webmcp). Only registered where the browser offers
// `modelContext`; everywhere else this file does nothing. All data comes from the same places the page
// uses — latest.json and changelog.md on this origin — so tools and page can never disagree.
(function () {
  'use strict';

  var mc = (typeof document !== 'undefined' && document.modelContext) ||
    (typeof navigator !== 'undefined' && navigator.modelContext);
  if (!mc || typeof mc.registerTool !== 'function') return;

  // Facts from site.json (generated by build.py).
  var FACTS = {
    "name": "Pegel",
    "summary": "Pegel is a free, open-source (MIT) system equalizer for Android 9 and later. It offers a ten-band equalizer (31 Hz to 16 kHz, ±12 dB in 0.5 dB steps) with a live response curve, 13 presets and your own presets, plus bass boost, loudness, a virtualizer, optional reverb and left/right balance. The whole sound can be saved as a profile, and each output — speaker, wired headphones, USB audio, each Bluetooth device — can have its own profile that Pegel applies when that output becomes active. Pegel does not process audio itself: it configures Android's own effects (DynamicsProcessing, Virtualizer, PresetReverb) on the global mix and on the audio sessions that music players announce, so it works without root and within the limits Android sets — apps that neither announce their session nor play through the global mix are not reached. Profiles, presets and settings can be backed up to one JSON file, and single profiles shared as .pegel files. There are no ads, no tracking and no account; the only network access is the update check, which can be switched off, and the checksum-verified update the app installs itself. Distributed as a signed APK through GitHub Releases.",
    "requirements": {
      "android": "Android 9+"
    },
    "platforms": [
      "Speaker",
      "Wired headphones",
      "USB audio",
      "Bluetooth"
    ],
    "features": [
      "Ten-band equalizer, 31 Hz to 16 kHz, ±12 dB in 0.5 dB steps, with a live response curve",
      "13 built-in presets and your own presets",
      "Bass boost with adjustable cutoff frequency (10–150 Hz) and maximum gain",
      "Loudness that pushes the gain into a limiter instead of clipping",
      "Virtualizer, optional reverb (rooms, halls, plate) and left/right balance",
      "Profiles: the whole sound under a name — load, save, rename, delete, discard changes",
      "A profile per output device: speaker, wired headphones, USB audio, each Bluetooth device",
      "Works on the global mix and on audio sessions announced by music players, switchable in Settings",
      "A status line that always says what the effects are attached to",
      "Backup and restore of all profiles, presets and settings as one JSON file; single profiles as .pegel files",
      "Starts again after a reboot and after an app update",
      "In-app updates: a daily check without any identifier, download with SHA-256 verification, installation through Android's installer; the check can be switched off",
      "A help page explaining which apps an equalizer can reach and what to try",
      "Material 3 Expressive interface, light and dark, optional Material You colours",
      "No ads, no tracking, no account, no paid version",
      "English and German, including per-app language on Android 13+"
    ],
    "limits": [
      "Android 9 or later only; not on Google Play — distributed as an APK through GitHub Releases.",
      "No root: Pegel reaches only audio that plays through the global mix or through a session a player announces. Apps with their own audio engine or copy protection may not be affected.",
      "Whether effects on the global mix are allowed depends on the device.",
      "Reverb works only on a player's own session, not on the global mix.",
      "Over Bluetooth, some phones need “Disable Bluetooth A2DP hardware offload” in the developer options before effects are audible.",
      "Two equalizers at once (including the one built into the phone) fight over the same audio session — use one.",
      "The interface is available in English and German only.",
      "It is not a parametric equalizer: the ten band frequencies are fixed."
    ],
    "targets": [
      "android"
    ],
    "signing": [
      {
        "what": "Signing certificate SHA-256",
        "value": "aa27ac4c8a8580905c0963cc362b943409fca43618dd1fabc0daf876ced8e282"
      }
    ],
    "links": {
      "page": "https://pegel.celox.io/",
      "download": "https://pegel.celox.io/download",
      "latest": "https://pegel.celox.io/latest.json",
      "markdown": "https://pegel.celox.io/index.md",
      "changelog": "https://pegel.celox.io/changelog.md",
      "skill": "https://pegel.celox.io/skills/get-pegel/SKILL.md",
      "source": "https://github.com/pepperonas/pegel",
      "licence": "https://github.com/pepperonas/pegel/blob/main/LICENSE"
    }
  };
  var SITE = FACTS.links.page.replace(/\/$/, '');
  var LANGS = ["en", "de", "es", "it", "fr"];

  function latest(signal) {
    return fetch('/latest.json', { cache: 'no-cache', signal: signal }).then(function (r) {
      if (!r.ok) throw new Error('latest.json: HTTP ' + r.status);
      return r.json();
    });
  }
  function json(v) { return JSON.stringify(v, null, 2); }
  var READ = { readOnlyHint: true };

  var tools = [
    {
      name: 'get_app_facts',
      description: 'What Pegel is: a one-paragraph summary, requirements, supported platforms, ' +
        'features, limits and the important links (download, source, changelog, licence).',
      inputSchema: { type: 'object', properties: {}, additionalProperties: false },
      annotations: READ,
      execute: function () { return Promise.resolve(json(FACTS)); }
    },
    {
      name: 'get_latest_release',
      description: 'The newest release of Pegel: version, publication date, release notes URL ' +
        'and every file with its download URL, size in bytes and SHA-256.',
      inputSchema: { type: 'object', properties: {}, additionalProperties: false },
      annotations: READ,
      execute: function (_input, opts) {
        return latest(opts && opts.signal).then(function (d) {
          return json({ version: d.version, published: d.published, notes: d.notes, assets: d.assets ||
            [{ target: FACTS.targets[0], name: d.name, url: d.url, size: d.size, sha256: d.sha256 }] });
        });
      }
    },
    {
      name: 'get_download_url',
      description: 'The direct download URL of the newest Pegel file for a platform (android), plus ' +
        'the stable link that always redirects to the newest file.',
      inputSchema: {
        type: 'object',
        properties: { platform: { type: 'string', enum: FACTS.targets, description: 'Target platform; default: ' + FACTS.targets[0] + '.' } },
        additionalProperties: false
      },
      annotations: READ,
      execute: function (input, opts) {
        return latest(opts && opts.signal).then(function (d) {
          var assets = d.assets || [{ target: FACTS.targets[0], name: d.name, url: d.url, size: d.size }];
          var want = (input && input.platform) || assets[0].target;
          var a = assets.filter(function (x) { return x.target === want; })[0] || assets[0];
          return json({ version: d.version, platform: a.target, file: a.name, url: a.url, size: a.size,
            stable_link: SITE + '/download/' + a.target });
        });
      }
    },
    {
      name: 'get_checksums',
      description: 'How to verify a downloaded Pegel file: the SHA-256 of every file of the newest release ' +
        'and the fixed signing facts.',
      inputSchema: { type: 'object', properties: {}, additionalProperties: false },
      annotations: READ,
      execute: function (_input, opts) {
        return latest(opts && opts.signal).then(function (d) {
          var assets = d.assets || [{ name: d.name, sha256: d.sha256 }];
          return json({ version: d.version,
            files: assets.map(function (a) { return { name: a.name, sha256: a.sha256 }; }),
            signing: FACTS.signing });
        });
      }
    },
    {
      name: 'get_changelog',
      description: 'The most recent entries of the Pegel changelog as Markdown.',
      inputSchema: {
        type: 'object',
        properties: { versions: { type: 'integer', minimum: 1, maximum: 10, description: 'How many versions (default 3).' } },
        additionalProperties: false
      },
      annotations: READ,
      execute: function (input, opts) {
        var n = Math.min(10, Math.max(1, (input && input.versions) || 3));
        return fetch('/changelog.md', { cache: 'no-cache', signal: opts && opts.signal }).then(function (r) {
          if (!r.ok) throw new Error('changelog.md: HTTP ' + r.status);
          return r.text();
        }).then(function (md) {
          var parts = md.split(/\n(?=## \[)/).slice(1).filter(function (s) { return !/^## \[Unreleased\]\s*$/.test(s.trim()); });
          return parts.slice(0, n).join('\n').trim();
        });
      }
    },
    {
      name: 'set_page_language',
      description: 'Show this page in another language (English, German, Spanish, Italian or French).',
      inputSchema: {
        type: 'object',
        properties: { language: { type: 'string', enum: LANGS, description: 'ISO 639-1 code.' } },
        required: ['language'],
        additionalProperties: false
      },
      annotations: { readOnlyHint: false },
      execute: function (input) {
        if (LANGS.indexOf(input.language) < 0) throw new Error('unsupported language: ' + input.language);
        if (typeof window.SITE_setLanguage === 'function') window.SITE_setLanguage(input.language);
        return Promise.resolve('Page language set to ' + input.language + '.');
      }
    }
  ];

  tools.forEach(function (t) {
    try { mc.registerTool(t); } catch (e) { /* a browser with an older WebMCP shape: skip that tool */ }
  });
})();
